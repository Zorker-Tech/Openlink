#!/usr/bin/env node
import assert from 'node:assert/strict'
import { randomBytes } from 'node:crypto'

function required(name) {
  const value = process.env[name]?.trim()
  if (!value) throw new Error(`${name} is required`)
  return value
}

const url = required('OPENLINK_PROJECT_SUPABASE_URL').replace(/\/$/, '')
const anonKey = required('OPENLINK_PROJECT_SUPABASE_ANON_KEY')
const serviceKey = required('OPENLINK_PROJECT_SUPABASE_SERVICE_KEY')
const databaseUrl = required('OPENLINK_PROJECT_SUPABASE_DATABASE_URL')
const marker = `e2e-${Date.now()}-${randomBytes(6).toString('hex')}`
const email = `${marker}@example.invalid`
const password = `A!${randomBytes(18).toString('base64url')}`
const keepFixtures = process.env.OPENLINK_PROJECT_SUPABASE_KEEP_FIXTURES === '1'

async function request(path, { method = 'GET', key = anonKey, token = key, body, headers = {} } = {}) {
  const response = await fetch(`${url}${path}`, {
    method,
    headers: { apikey: key, Authorization: `Bearer ${token}`, ...(body === undefined ? {} : { 'content-type': 'application/json' }), ...headers },
    body: body === undefined ? undefined : JSON.stringify(body),
    signal: AbortSignal.timeout(30_000),
  })
  const text = await response.text()
  let value
  try { value = text ? JSON.parse(text) : null } catch { value = text }
  if (!response.ok) throw new Error(`${method} ${path} returned ${response.status}: ${typeof value === 'string' ? value.slice(0, 500) : JSON.stringify(value).slice(0, 500)}`)
  return { response, value }
}

async function requestWhenFunctionRouteReady(path, options) {
  let lastError
  for (let attempt = 0; attempt < 30; attempt += 1) {
    try { return await request(path, options) } catch (error) {
      lastError = error
      // Edge Runtime starts its HTTP listener before the function bundle has
      // completed loading. Envoy reports that narrow window as a 503 reset;
      // retain a bounded, function-specific readiness wait rather than
      // weakening the E2E requirement to a container/TCP health signal.
      if (!/returned 503:.*(?:connection termination|upstream connect error)/i.test(String(error))) throw error
      await new Promise((resolveDelay) => setTimeout(resolveDelay, 1_000))
    }
  }
  throw lastError
}

const { default: postgres } = await import('postgres')
const sql = postgres(databaseUrl, { max: 1, connect_timeout: 10, idle_timeout: 5 })
let accessToken
try {
  await request('/auth/v1/health')
  const signup = await request('/auth/v1/signup', { method: 'POST', body: { email, password } })
  accessToken = signup.value.access_token
  if (!accessToken) accessToken = (await request('/auth/v1/token?grant_type=password', { method: 'POST', body: { email, password } })).value.access_token
  assert.ok(accessToken, 'Auth signup/login did not return an access token')

  await sql.unsafe(`
    create table if not exists public.openlink_e2e_items (
      id bigint generated by default as identity primary key,
      owner uuid not null references auth.users(id),
      marker text not null unique
    );
    alter table public.openlink_e2e_items enable row level security;
    drop policy if exists openlink_e2e_owner_all on public.openlink_e2e_items;
    create policy openlink_e2e_owner_all on public.openlink_e2e_items for all to authenticated using ((select auth.uid()) = owner) with check ((select auth.uid()) = owner);
    grant select, insert, update, delete on public.openlink_e2e_items to authenticated;
    grant usage, select on sequence public.openlink_e2e_items_id_seq to authenticated;
    notify pgrst, 'reload schema';
  `)
  await new Promise((resolve) => setTimeout(resolve, 2_000))
  const user = (await request('/auth/v1/user', { token: accessToken })).value
  await request('/rest/v1/openlink_e2e_items', { method: 'POST', token: accessToken, body: { owner: user.id, marker }, headers: { Prefer: 'return=representation' } })
  const selected = await request(`/rest/v1/openlink_e2e_items?marker=eq.${encodeURIComponent(marker)}&select=id,owner,marker`, { token: accessToken })
  assert.equal(selected.value[0]?.marker, marker)
  const anonymous = await request(`/rest/v1/openlink_e2e_items?marker=eq.${encodeURIComponent(marker)}&select=id`, {})
  assert.deepEqual(anonymous.value, [], 'RLS exposed authenticated data to anon')

  const bucket = marker.slice(0, 48)
  await request('/storage/v1/bucket', { method: 'POST', key: serviceKey, body: { id: bucket, name: bucket, public: false } })
  const bytes = Buffer.from(`OpenLink Project Supabase ${marker}`)
  const upload = await fetch(`${url}/storage/v1/object/${bucket}/persistence.txt`, { method: 'POST', headers: { apikey: serviceKey, Authorization: `Bearer ${serviceKey}`, 'content-type': 'text/plain', 'x-upsert': 'true' }, body: bytes, signal: AbortSignal.timeout(30_000) })
  assert.ok(upload.ok, `Storage upload returned ${upload.status}: ${(await upload.text()).slice(0, 500)}`)
  const download = await fetch(`${url}/storage/v1/object/authenticated/${bucket}/persistence.txt`, { headers: { apikey: serviceKey, Authorization: `Bearer ${serviceKey}` }, signal: AbortSignal.timeout(30_000) })
  assert.ok(download.ok, `Storage download returned ${download.status}`)
  assert.equal(Buffer.from(await download.arrayBuffer()).toString(), bytes.toString())

  const edge = await requestWhenFunctionRouteReady('/functions/v1/hello', { method: 'POST', token: accessToken, body: { name: marker } })
  assert.match(String(edge.value), /Hello from Edge Functions/, 'Edge Function returned an unexpected body')
  await request('/pg/health', { key: serviceKey })
  const studio = await fetch(`${url}/`, {
    signal: AbortSignal.timeout(30_000),
    headers: { Authorization: `Basic ${Buffer.from(`supabase:${required('OPENLINK_PROJECT_SUPABASE_DASHBOARD_PASSWORD')}`).toString('base64')}` },
  })
  if (!studio.ok) {
    const body = await studio.text().catch(() => '')
    throw new Error(`Studio returned ${studio.status}: ${body.slice(0, 500)}`)
  }
  const db = await sql`select current_setting('server_version_num')::int as version, ${marker}::text as marker`
  assert.ok(db[0].version >= 170000)
  assert.equal(db[0].marker, marker)

  // Verify the Realtime service is accessible and its tenant is configured.
  // The Realtime health endpoint proves the service accepted the JWT secret,
  // created the tenant, and is ready to accept WebSocket subscriptions.
  // When OPENLINK_PROJECT_SUPABASE_REALTIME_URL is set, connect directly to
  // the Realtime container (bypassing the API gateway port forward, which
  // may not support WebSocket upgrade on all hypervisors).
  const realtimeDirectUrl = process.env.OPENLINK_PROJECT_SUPABASE_REALTIME_URL
  const realtimeHealthUrl = realtimeDirectUrl
    ? `${realtimeDirectUrl}/api/tenants/realtime-dev/health`
    : `${url}/realtime/v1/api/tenants/realtime-dev/health`
  const realtimeHealth = await fetch(realtimeHealthUrl, {
    headers: { Authorization: `Bearer ${anonKey}` },
    signal: AbortSignal.timeout(10_000),
  })
  if (!realtimeHealth.ok) throw new Error(`Realtime health check returned ${realtimeHealth.status}`)
  process.stdout.write(`${JSON.stringify({ ok: true, marker, auth: true, restRls: true, storage: true, realtime: true, functions: true, studio: true, meta: true, postgres: true })}\n`)
} finally {
  if (accessToken && !keepFixtures) await request(`/rest/v1/openlink_e2e_items?marker=eq.${encodeURIComponent(marker)}`, { method: 'DELETE', token: accessToken }).catch(() => undefined)
  await sql.end({ timeout: 5 })
}
